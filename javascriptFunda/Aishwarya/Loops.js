//for loop
for(let i = 1; i <= 5; i++) {
    console.log(i);
}


//while loop
let i = 1;
while(i <= 5) {
    console.log(i);
    i++;
}


//do while
let i = 1;
do {
    console.log(i);
    i++;
}
while(i <= 5);


//for of loop
let fruits = ["Apple", "Mango", "Banana"];

for(let fruit of fruits) {
    console.log(fruit);
}


//for in loop
let student = {
    name: "Aishu",
    age: 23
};
for(let key in student) {
    console.log(key);
}


