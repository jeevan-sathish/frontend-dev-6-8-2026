//Arth operator
let a = 10;
let b = 3;
console.log(a + b);  
console.log(a - b);  
console.log(a * b);  
console.log(a / b);  
console.log(a % b);  
console.log(a ** b); 

//Assigment operator
let x = 10;
x += 5;   
x -= 2;   
x *= 2;   
x /= 2;  

//comparision operator
console.log(10 > 5);     
console.log(10 < 5);     
console.log(10 == "10"); 
console.log(10 === "10");

//logical operator
console.log(true && true);
console.log(true || false);
console.log(!true);

//inc and dec operator
let x = 5;
x++;
console.log(x);

let x = 5;
x--;
console.log(x);

//string operator
let firstName = "Aishu";
let lastName = "C";
console.log(firstName + lastName);

//Ternary operator
let age = 20;
let result = age >= 18
    ? "Adult"
    : "Minor";
console.log(result);

//typeof op
console.log(typeof "Hello");
console.log(typeof 23);
console.log(typeof true);